// Message d'erreur AFFICHABLE : les codes d'erreur stables renvoyés par le
// backend (ex. `discord_reconnecting` pendant une re-init Vesktop après une
// bascule Bureau↔gamemode) sont traduits au lieu d'exposer l'exception Python
// brute dans le QAM.
export function errText(e: unknown): string {
  const s = String(e);
  if (s.includes("discord_reconnecting")) return t("discord_reconnecting");
  // #28 : les stores Vencord pas encore résolus, et l'échec générique côté
  // backend. Sans ces deux branches l'utilisateur recevait la TypeError ou la
  // trace Python crue (« error: python exception »).
  if (s.includes("stores_not_ready")) return t("discord_starting");
  if (s.includes("guilds_failed")) return t("guilds_failed");
  return t("error") + s;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  if (_locale === null) _locale = detectLocale();
  let s = T[_locale][key] ?? T.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  return s;
}
